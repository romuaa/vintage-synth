/** |H| in dB of the two-pole low-pass (fc, Q) at the estimator's bins (unity DC gain). */
tr::Response twoPole (double fc, double q)
{
    tr::Response r {};
    for (int k = 0; k < tr::kSpecBins; ++k)
    {
        const std::complex<double> s (0.0, tr::binHz (k) / fc);
        r[static_cast<std::size_t> (k)] = 20.0 * std::log10 (std::abs (1.0 / (s * s + s / q + 1.0)));
    }
    return r;
}

/** True -3 dB point of the two-pole (fc, Q) against its DC gain. */
double trueMinus3 (double fc, double q)
{
    const double a = 2.0 - 1.0 / (q * q);
    return fc * std::sqrt ((a + std::sqrt (a * a + 4.0)) / 2.0);
}

struct Estimate
{
    bool ok = false;
    double corner = 0.0, peak = 0.0;
};

Estimate estimate (const tr::Response& r)
{
    const auto c = tr::lowpassCorner (r);
    const auto p = tr::resonancePeak (r);
    Estimate e;
    e.ok = c.found && p.found;
    e.corner = c.hz;
    e.peak = p.db;
    return e;
}

/** The two-pole whose estimated corner and peak come closest to (corner, peak), searched over the lower pole frequency
    w = fc Q and the sum of the poles p = fc / Q (both regimes: complex poles and far-apart real poles): a coarse grid,
    then a coarse-to-fine refinement from each of its best few points (the cost has several basins). */
struct Required
{
    double fc = 0.0, q = 0.0, cornerErr = 1.0, peakErr = 1.0e9, cost = 1.0e300;
};

Required evaluateTwoPole (double lw, double lp, double corner, double peak)
{
    Required r;
    const double w = std::exp (lw), p = std::exp (lp);
    r.fc = std::sqrt (w * p);
    r.q = std::sqrt (w / p);
    if (r.q < 0.005 || r.q > 6.0)
        return r;
    const auto e = estimate (twoPole (r.fc, r.q));
    if (! e.ok)
        return r;
    r.cornerErr = std::log (e.corner / corner);
    r.peakErr = e.peak - peak;
    r.cost = (r.cornerErr / 0.05) * (r.cornerErr / 0.05) + r.peakErr * r.peakErr;
    return r;
}

/** dB rms between a response (minus its plateau) and the two-pole (fc, Q), over the bins within 24 dB of the plateau. */
double shapeRms (const tr::Response& ref, double plateau, double fc, double q)
{
    const auto two = twoPole (fc, q);
    double e2 = 0.0;
    int nb = 0;
    for (int k = 0; k < tr::kSpecBins; ++k)
    {
        const double v = ref[static_cast<std::size_t> (k)] - plateau;
        if (std::isnan (v) || v < -24.0)
            continue;
        e2 += (v - two[static_cast<std::size_t> (k)]) * (v - two[static_cast<std::size_t> (k)]);
        ++nb;
    }
    return nb > 0 ? std::sqrt (e2 / nb) : 0.0;
}

/** Several two-poles can give the same corner and peak; among the refined candidates that match (corner within 0.5 %,
    peak within 0.05 dB) the one closest in shape to the reference's response is taken, otherwise the closest match. */
Required requiredTwoPole (double corner, double peak, const tr::Response& ref, double plateau)
{
    const double lw0 = std::log (corner), lp0 = std::log (corner);
    struct Point
    {
        double lw, lp, cost;
    };
    std::vector<Point> coarse;
    const int n = 40;
    for (int i = 0; i <= n; ++i)
        for (int j = 0; j <= n; ++j)
        {
            const double lw = lw0 + std::log (8.0) * (2.0 * i / n - 1.0);
            const double lp = lp0 - std::log (4.0) + std::log (1600.0) * j / n;
            coarse.push_back ({ lw, lp, evaluateTwoPole (lw, lp, corner, peak).cost });
        }
    std::sort (coarse.begin(), coarse.end(), [] (const Point& x, const Point& y) { return x.cost < y.cost; });
    Required best, bestExact;
    double bestShape = 1.0e300;
    for (std::size_t s = 0; s < std::min<std::size_t> (12, coarse.size()); ++s)
    {
        double lwC = coarse[s].lw, lpC = coarse[s].lp, sw = std::log (8.0) / n * 2.0, sp = std::log (1600.0) / n * 2.0;
        Required local = evaluateTwoPole (lwC, lpC, corner, peak);
        for (int round = 0; round < 10; ++round)
        {
            const int m = 6;
            for (int i = -m; i <= m; ++i)
                for (int j = -m; j <= m; ++j)
                {
                    const double lw = lwC + sw * i / m, lp = lpC + sp * j / m;
                    const auto r = evaluateTwoPole (lw, lp, corner, peak);
                    if (r.cost < local.cost)
                    {
                        local = r;
                        lwC = lw;
                        lpC = lp;
                    }
                }
            sw *= 0.4;
            sp *= 0.4;
        }
        if (local.cost < best.cost)
            best = local;
        if (std::abs (local.cornerErr) < 0.005 && std::abs (local.peakErr) < 0.05)
        {
            const double sh = shapeRms (ref, plateau, local.fc, local.q);
            if (sh < bestShape)
            {
                bestShape = sh;
                bestExact = local;
            }
        }
    }
    return bestShape < 1.0e299 ? bestExact : best;
}

struct OperatingPoint
{
    double dc = 0.0, rms = 0.0;
    int voices = 0, cutoff = 0, resonance = 0;
};

/** The filter bus our chain feeds over a segment's frames (render units), and the filter registers at its middle. */
std::vector<OperatingPoint> operatingPoints (const Rendered& r)
{
    const auto rec = recordChip (r.trace, 192000.0, true);
    std::vector<OperatingPoint> out;
    if (! rec.perVoice)
        return out;
    const auto& envTable = ch::render::tablesFor (rec.model, ch::ShapeSet::fitted).envelope;
    ch::OutputStage stage;
    stage.prepare (rec.model, rec.rate, true);
    for (const auto& seg : r.reference.segments)
    {
        const std::size_t a = static_cast<std::size_t> (seg.firstFrame) * tr::kSpecHop * 4;
        const std::size_t b = std::min (rec.samples, static_cast<std::size_t> (seg.endFrame) * tr::kSpecHop * 4);
        double s1 = 0.0, s2 = 0.0;
        int maxVoices = 0;
        for (std::size_t j = a; j < b; ++j)
        {
            const auto& q = rec.regs[j];
            stage.setRouting (q[2]);
            stage.setModeVolume (q[3]);
            float env = 0.0f, audio = 0.0f;
            int voices = 0;
            for (std::size_t v = 0; v < 3; ++v)
            {
                if (((q[2] >> v) & 1) == 0)
                    continue;
                ++voices;
                const float e = envTable[rec.counters[j][v]];
                env += e;
                audio += ch::OutputStage::shapeVoice (rec.model, rec.voice[v][j], e);
            }
            const double x = stage.filterBusLevel (audio, env);
            s1 += x;
            s2 += x * x;
            maxVoices = std::max (maxVoices, voices);
        }
        OperatingPoint op;
        const double n = static_cast<double> (std::max<std::size_t> (1, b - a));
        op.dc = s1 / n;
        op.rms = std::sqrt (std::max (0.0, s2 / n - op.dc * op.dc));
        op.voices = maxVoices;
        const auto& mid = rec.regs[std::min (rec.samples - 1, (a + b) / 2)];
        op.cutoff = (mid[0] & 7) | (mid[1] << 3);
        op.resonance = mid[2] >> 4;
        out.push_back (op);
    }
    return out;
}

struct Totals
{
    double total = 0.0, chain = 0.0, shape = 0.0, coef = 0.0;
    int outside = 0;
};

void diagnose (const char* filtered, const char* bypass, Totals& sum)
{
    const std::string filteredName (filtered), bypassName (bypass); // no temporary argument (GCC 13 -Wdangling-reference)
    const auto& f = renderedTrace (kDir, filteredName);
    const auto& b = renderedTrace (kDir, bypassName);
    if (! f.ok || ! b.ok)
        SKIP (f.why << " " << b.why);
    const auto ops = operatingPoints (f);
    REQUIRE (ops.size() == f.reference.segments.size());
    std::printf ("[s3a-diag] %s: seg FC res | DC rms voices | corner ref ours | as-built fc Q | required fc Q (shape rms dB) | "
                 "total = chain + shape + coef (fc part, Q part), log-%%\n",
                 filtered);
    for (std::size_t i = 0; i < f.reference.segments.size(); ++i)
    {
        const auto& op = ops[i];
        const auto ref = tr::filterResponse (f.reference.segments[i], b.reference.segments[i]);
        const auto ours = tr::filterResponse (f.ours.segments[i], b.ours.segments[i]);
        const auto er = estimate (ref), eo = estimate (ours);
        const char* name = f.reference.segments[i].name.c_str();
        if (! er.ok || ! eo.ok)
        {
            std::printf ("[s3a-diag] %s %s FC %4d res %2d: no corner the estimator resolves (%s); not diagnosed\n", filtered, name, op.cutoff,
                         op.resonance, er.ok ? "ours" : "reference");
            continue;
        }
        ch::Filter asb;
        asb.prepare (ch::Model::A, 192000.0);
        asb.setCutoff (static_cast<float> (op.cutoff));
        asb.setResonance (op.resonance);
        const double fA = asb.cutoffHz(), qA = asb.q();
        const auto eA = estimate (twoPole (fA, qA));
        const auto cRef = tr::lowpassCorner (ref);
        const auto req = requiredTwoPole (er.corner, er.peak, ref, cRef.plateauDb);
        INFO (filtered << " " << name);
        // Sanity: a two-pole reproducing the reference's corner and peak under the gates' estimator exists (found for
        // every segment when this test was written; failing means the estimator, the data or the search changed).
        CHECK (std::abs (req.cornerErr) < 0.01);
        CHECK (std::abs (req.peakErr) < 0.25);
        CHECK (eA.ok);
        const auto eR = estimate (twoPole (req.fc, req.q));
        const double tA = trueMinus3 (fA, qA), tR = trueMinus3 (req.fc, req.q);
        const double total = 100.0 * std::log (eo.corner / er.corner);
        const double chain = 100.0 * std::log (eo.corner / eA.corner);
        const double shape = 100.0 * (std::log (eA.corner / tA) - std::log (eR.corner / tR));
        const double coef = 100.0 * std::log (tA / tR);
        const double coefFc = 100.0 * std::log (fA / req.fc);
        // chain + shape + coef = total - 100 ln (eR.corner / er.corner): exact up to the search's residual (req.cornerErr)
        // shape: how far the reference's response is from the required two-pole (bins within 24 dB of the plateau)
        const double shape2 = shapeRms (ref, cRef.plateauDb, req.fc, req.q);
        const bool outside = std::abs (eo.corner / er.corner - 1.0) > 0.05;
        std::printf ("[s3a-diag] %s %s FC %4d res %2d | DC %.2f rms %.3f n %d | corner ref %7.0f ours %7.0f | as-built fc %7.0f Q %.3f | "
                     "required fc %8.0f Q %.3f (%.2f dB) | %+7.1f = %+6.1f %+6.1f %+7.1f (%+7.1f, %+7.1f)%s\n",
                     filtered, name, op.cutoff, op.resonance, op.dc, op.rms, op.voices, er.corner, eo.corner, fA, qA, req.fc, req.q,
                     shape2, total, chain, shape, coef, coefFc, coef - coefFc, outside ? "  OUTSIDE" : "");
        if (outside)
        {
            sum.total += std::abs (total);
            sum.chain += std::abs (chain);
            sum.shape += std::abs (shape);
            sum.coef += std::abs (coef);
            ++sum.outside;
        }
        // Sanity on the operating point (render units, our model's voice DC): one voice at sustain 3 / 8 / 15 sits at
        // about 0.47 / 0.59 / 0.77, three voices at sustain 5 / 11 at about 1.56 / 2.01.
        CHECK (op.voices >= 1);
        CHECK (op.dc > 0.3);
        CHECK (op.dc < 2.5);
    }
}
