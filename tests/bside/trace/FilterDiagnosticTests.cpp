// S3a diagnostic (docs/decisions.md "B-Side S3a round 2" R1, R2, R12): where the Model A corner errors of the committed
// gate traces come from, from committed data only (tests/bside/reference/a_s3a_*). Reported, not gated; the only
// assertions are sanity checks that can fail for real (see each CHECK).
//
// Per segment of a_s3a_res_a, a_s3a_level_a, a_s3a_voices_a and a_s3a_cutoff_a:
// - the operating point our chain feeds the filter: the filter bus's mean (DC) and rms swing in render units over the
//   segment's frames, and the number of voices routed (AnalogChain.h per voice; OutputStage::filterBusLevel);
// - the as-built filter's coefficients at the segment's cutoff and resonance (Filter::cutoffHz, Filter::q);
// - the REQUIRED two-pole: the low-pass (fc, Q) whose response gives the reference's corner and peak under the gates'
//   own estimator (AnalogMeasure.h), found by a search over the poles' product and sum; and how far the reference's
//   committed response is from that two-pole (dB rms over the bins within 24 dB of the plateau);
// - the corner error ln (ours / reference) split exactly into
//     chain  = ln (C_ours / E_asb)                    our chain against its own linear two-pole (level effects, power ratio)
//     shape  = ln (E_asb / T_asb) - ln (E_req / T_req) the estimator's bias on the as-built's shape minus its bias on the
//                                                      required shape (zero when the shapes agree)
//     coef   = ln (T_asb / T_req)                      the coefficients: the true -3 dB points of the as-built and required
//                                                      two-poles (split further into its fc and its Q part)
//   where C is the estimator on a spectrum, E the estimator on an analytic two-pole and T a two-pole's true -3 dB point.
// What separates the reference's DC shift, swing and resonance law needs reference data the repository does not hold
// (generated by the adapter on purpose-made traces): that part of the diagnosis lives outside the repository.

